LANG_NAMES = {
    "ro": "Română",
    "en": "English",
    "fr": "Français",
    "es": "Español",
    "de": "Deutsch",
    "it": "Italiano",
    "pt": "Português",
    "nl": "Nederlands",
    "pl": "Polski",
    "ru": "Русский"
}

LANG_ORDER = ["ro", "en", "fr", "es", "de", "it", "pt", "nl", "pl", "ru"]

_CUR = {"code": "ro"}

_CFG = os.path.join(os.environ.get("APPDATA") or os.path.expanduser("~"),
                    "PDFTool", "settings.json")


def current():
    return _CUR["code"]


def t(s):
    """Traduce un text in limba curenta."""
    if _CUR["code"] == "ro":
        return s
    return TR.get(_CUR["code"], {}).get(s, s)


def set_lang(code):
    if code in LANG_NAMES:
        _CUR["code"] = code


def _read_cfg():
    try:
        with open(_CFG, encoding="utf-8") as fh:
            d = json.load(fh)
        return d if isinstance(d, dict) else {}
    except Exception:
        return {}


def _write_cfg(data):
    try:
        os.makedirs(os.path.dirname(_CFG), exist_ok=True)
        with open(_CFG, "w", encoding="utf-8") as fh:
            json.dump(data, fh, ensure_ascii=False)
    except Exception:
        pass


def save_pref(code):
    d = _read_cfg()
    d["lang"] = code
    _write_cfg(d)


def panel_width(implicit=430):
    """Cat de lat a fost lasat panoul din dreapta."""
    try:
        v = int(_read_cfg().get("panel_width") or implicit)
    except Exception:
        return implicit
    return max(320, min(760, v))


def set_panel_width(px):
    d = _read_cfg()
    d["panel_width"] = max(320, min(760, int(px)))
    _write_cfg(d)


def check_updates():
    """Cauta programul singur versiuni noi la pornire? Implicit da."""
    return bool(_read_cfg().get("check_updates", True))


def set_check_updates(pornit):
    d = _read_cfg()
    d["check_updates"] = bool(pornit)
    _write_cfg(d)


def guide_seen():
    """True daca ghidul a mai fost aratat pe acest calculator."""
    return bool(_read_cfg().get("guide_seen"))


def mark_guide_seen():
    d = _read_cfg()
    d["guide_seen"] = True
    d.setdefault("lang", _CUR["code"])
    _write_cfg(d)


def load_pref():
    """Limba salvata, altfel cea a Windows-ului, altfel engleza."""
    c = _read_cfg().get("lang")
    if c in LANG_NAMES:
        return c
    c = system_lang()
    if c in LANG_NAMES:
        return c
    return "en"


def system_lang():
    """Limba Windows-ului, ca un cod de doua litere.

    Intreaba sistemul direct. GetUserDefaultLocaleName exista in orice
    Windows si nu dispare niciodata. locale.getdefaultlocale() ramane
    doar ca plasa de siguranta: e marcata ca invechita si va fi scoasa
    dintr-o versiune viitoare de Python.
    """
    try:
        import ctypes
        buf = ctypes.create_unicode_buffer(85)
        if ctypes.windll.kernel32.GetUserDefaultLocaleName(buf, 85):
            return buf.value.replace("-", "_").split("_")[0].lower()
    except Exception:
        pass
    try:
        return (locale.getdefaultlocale()[0] or "").split("_")[0].lower()
    except Exception:
        return ""


